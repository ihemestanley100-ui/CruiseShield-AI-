def validate(data: dict) -> list[str]:
    problems = []
    ids = [r["id"] for r in data["rows"]]
    if len(ids) != len(set(ids)):
        problems.append("duplicate requirement IDs")
    for row in data["rows"]:
        if row["status"] not in STATUSES:
            problems.append(f"{row['id']}: bad status {row['status']}")
        for ref in (row["implementation"], row["test"]):
            for part in ref.split():
                if not part:
                    continue
                if (ROOT / part).exists():
                    continue
                problems.append(f"{row['id']}: missing ref {part}")
        if row["status"] == "CLOSED_VERIFIED" and not row["evidence"]:
            problems.append(f"{row['id']}: verified without evidence")
        if row["status"] in ("BLOCKED_EXTERNAL_DEPENDENCY",
                             "AWAITING_OWNER_APPROVAL"):
            if row["next"]:
                continue
            problems.append(f"{row['id']}: blocked without next action")
    ind_rows = [r for r in data["rows"] if r["id"].startswith("IND-")]
    if len(ind_rows) != 45:
        problems.append(f"industry rows: {len(ind_rows)} != 45")
    return problems


def main() -> int:
    data = build()
    if "--check" in sys.argv:
        current = json.loads(OUT.read_text(encoding="utf-8"))
        problems = validate(current)
        if problems:
            print("\n".join(problems))
            return 1
        print(f"matrix valid: {len(current['rows'])} rows")
        return 0
    problems = validate(data)
    if problems:
        print("\n".join(problems))
        return 1
    OUT.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    counts: dict = {}
    for row in data["rows"]:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    print(f"wrote {OUT.name}: {len(data['rows'])} rows {counts}")
    return 0


